#!/usr/bin/env python3
"""Generate main/board_pins.h from caliper/hardware/design/nets.py (GPIO and I2C_ADDR).

    python tools/gen_pins.py            # write main/board_pins.h
    python tools/gen_pins.py --check    # exit 1 if the committed header is stale

The header carries a SHA-256 of the inputs so the build (main/CMakeLists.txt) can tell when
nets.py changed without the header being regenerated.
"""
import argparse
import hashlib
import pathlib
import re
import runpy
import sys

HERE = pathlib.Path(__file__).resolve().parent
FW = HERE.parent
DEFAULT_NETS = FW.parent / "hardware" / "design" / "nets.py"
DEFAULT_OUT = FW / "main" / "board_pins.h"

# Nets the firmware needs; generation fails if one disappears from nets.py.
REQUIRED = [
    "CAP_RX", "FG_ALRT_N", "CHG_INT_N", "MAG_A", "MAG_B", "MAG_IDX", "MAG_CLK", "MAG_DO", "MAG_CSN",
    "MAG_INC_N", "MAG_DEC_N", "SNS_PWR_EN", "I2C_SDA", "I2C_SCL", "IMU_INT1", "IMU_INT2",
    "BTN_ZERO_N", "BTN_HOLD_N", "BTN_MODE_N", "USB_DM", "USB_DP", "LCD_SCK", "LCD_MOSI", "LCD_CS_N",
    "LCD_DC", "LCD_RST_N", "LCD_BL", *[f"CAP_TX{i}" for i in range(8)], "BUZZ", "RGB_DIN",
]
REQUIRED_I2C = ["BQ25180", "MAX17048", "LSM6DSO", "IIS2MDC"]


def macro(net: str) -> str:
    return "PIN_" + re.sub(r"[^A-Z0-9]", "_", net.upper()).strip("_")


def render(nets_path: pathlib.Path) -> str:
    src = nets_path.read_bytes()
    ns = runpy.run_path(str(nets_path))
    gpio = ns["GPIO"]
    i2c = ns["I2C_ADDR"]
    missing = [n for n in REQUIRED if n not in gpio] + [d for d in REQUIRED_I2C if d not in i2c]
    if missing:
        raise SystemExit(f"gen_pins: nets.py lacks {', '.join(missing)}")
    if 26 in gpio.values():
        raise SystemExit("gen_pins: GPIO26 is the in-package PSRAM CS and must not be used")
    digest = hashlib.sha256(src + pathlib.Path(__file__).read_bytes()).hexdigest()[:16]

    lines = [
        "/*",
        " * GENERATED by firmware/tools/gen_pins.py from caliper/hardware/design/nets.py. Do not edit.",
        f" * nets.py REV {ns.get('REV', '?')} {ns.get('DATE', '')}",
        " */",
        "#pragma once",
        "",
        f'#define BOARD_PINS_HASH "{digest}"',
        f'#define BOARD_REV "{ns.get("REV", "?")}"',
        "",
        "/* GPIO number per net (ESP32-S3-MINI-1) */",
    ]
    width = max(len(macro(n)) for n in gpio)
    for net, num in sorted(gpio.items(), key=lambda kv: kv[1]):
        lines.append(f"#define {macro(net):<{width}} {num:2d}  /* {net} */")
    lines += ["", "/* 7-bit I2C addresses */"]
    for dev, addr in sorted(i2c.items()):
        lines.append(f"#define I2C_ADDR_{dev.upper():<10} 0x{addr:02X}")
    lines += [
        "",
        "/* CAP_TX0..7 in phase order, for the dedicated-GPIO bundle */",
        "#define PIN_CAP_TX_LIST { " + ", ".join(macro(f"CAP_TX{i}") for i in range(8)) + " }",
        "",
        "/* every GPIO above, for checks (test/host/test_pin_plan.c: each one is in the pin plan) */",
        f"#define BOARD_PINS_COUNT {len(gpio)}",
        "#define BOARD_PINS_ALL { \\",
    ]
    nets = [n for n, _ in sorted(gpio.items(), key=lambda kv: kv[1])]
    for i in range(0, len(nets), 6):
        chunk = ", ".join(macro(n) for n in nets[i:i + 6])
        lines.append(f"    {chunk}{',' if i + 6 < len(nets) else ''} \\")
    lines += [
        "}",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--nets", type=pathlib.Path, default=DEFAULT_NETS)
    ap.add_argument("--out", type=pathlib.Path, default=DEFAULT_OUT)
    ap.add_argument("--check", action="store_true", help="fail if the header is out of date")
    args = ap.parse_args()
    text = render(args.nets)
    if args.check:
        current = args.out.read_text(encoding="utf-8") if args.out.exists() else ""
        if current != text:
            print(f"gen_pins: {args.out} is stale; run: python tools/gen_pins.py", file=sys.stderr)
            return 1
        print("gen_pins: board_pins.h up to date")
        return 0
    args.out.write_text(text, encoding="utf-8", newline="\n")
    print(f"gen_pins: wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
