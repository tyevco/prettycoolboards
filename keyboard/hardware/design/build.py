#!/usr/bin/env python3
"""Generate the PrettyCool Keyboard rev A KiCad schematics (and their libraries) from the sheet modules.

usage: python keyboard/hardware/design/build.py [--board NAME] [--only MODULE ...] [--out DIR] [--no-erc] [--render]

Boards and their sheet modules: sheets/__init__.py PROJECTS (a board whose modules do not exist yet is skipped when
building every board, and refused when named). Per board: the wiring check (Design.check(): the wiring rule R1-R6 of
tools/README.md, no label fallback, no waiver), the sheets written to keyboard/hardware/kicad/<board>/, kicad-cli ERC
(only the waivers listed below, each with its reason), the netlist and, with --render, a PDF and a PNG per sheet.
Exit code 1 on any CHECK error or unwaived ERC violation.

Adapted from caliper/hardware/design/build.py; the shared toolchain is <repo>/tools.
"""

from __future__ import annotations

import argparse
import fnmatch
import importlib
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
HW = os.path.dirname(HERE)                                  # keyboard/hardware
REPO = os.path.dirname(os.path.dirname(HW))                 # repo root
sys.path.insert(0, os.path.join(REPO, "tools"))
sys.path.insert(0, HERE)

import fpgen  # noqa: E402
import pcbgen  # noqa: E402
import schgen  # noqa: E402
import symgen  # noqa: E402
import symlib  # noqa: E402

from sheets import PROJECTS  # noqa: E402

LIB = "keyboard"
UUID_NS = "prettycool-keyboard"
DEFAULT_OUT = os.path.join(HW, "kicad")
COMPANY = "PrettyCool Boards"
DEFAULT_REV, DEFAULT_DATE = "A", "2026-11-27"


def project_name(board):
    return f"prettycool-keyboard-{board}"


def uuid_namespace(board):
    """Every generated UUID (schematic and board) is namespaced per board: two projects never share one."""
    return f"{UUID_NS}/{board}"


# Intended connections that KiCad's pin-type matrix flags: (violation, {(ref, pin), ...} or "*", reason).
# A waived violation is reported as "waived", never silently dropped; any other pins in the same violation keep it an
# error. One list per board, so a reference designator reused on another board cannot waive the wrong part.
BOARD_ERC_WAIVERS: dict[str, list] = {
    "motherboard": [],
    "test-coupon": [],
    "coupon-hall": [],
    "coupon-tmr": [],
    "coupon-shear": [],
    "coupon-coil": [],
    "coupon-haptics": [],
    "latency-rig": [],
}


def sheet_modules(board):
    """The board's sheet module names, in page order ([] if none exists yet)."""
    spec = PROJECTS[board]["sheets"]
    if isinstance(spec, str):            # a glob over sheets/*.py, ordered by the module's PAGE, then its name
        names = sorted(f[:-3] for f in os.listdir(os.path.join(HERE, "sheets"))
                       if f.endswith(".py") and fnmatch.fnmatch(f[:-3], spec))
        mods = [importlib.import_module(f"sheets.{n}") for n in names]
        return [m.__name__.split(".")[-1] for m in sorted(mods, key=lambda m: (getattr(m, "PAGE", 99), m.__name__))]
    return [n for n in spec if os.path.exists(os.path.join(HERE, "sheets", n + ".py"))]


def load_modules(names):
    return [importlib.import_module(f"sheets.{n}") for n in names]


def build_libraries(mods, out):
    libdir = os.path.join(out, "lib")
    os.makedirs(libdir, exist_ok=True)
    sym_path = os.path.join(libdir, LIB + ".kicad_sym")
    fp_dir = os.path.join(libdir, LIB + ".pretty")
    syms, seen = [], set()
    for m in mods:
        for spec in getattr(m, "SYMBOLS", []):
            if spec["name"] in seen:
                continue
            seen.add(spec["name"])
            syms.append(symgen.box_symbol(**spec))
        if hasattr(m, "footprints"):
            m.footprints(fpgen, fp_dir)
    symgen.write_library(sym_path, syms, generator="prettycool_keyboard_symgen")
    symlib.register_library(LIB, sym_path)
    return {
        "sym": {LIB: "${KIPRJMOD}/lib/" + LIB + ".kicad_sym"},
        "fp": {LIB: "${KIPRJMOD}/lib/" + LIB + ".pretty"},
    }


def _union(mods, attr):
    out = []
    for m in mods:
        for n in getattr(m, attr, []):
            if n not in out:
                out.append(n)
    return out


def make_design(board, mods):
    title = PROJECTS[board]["title"]
    rev = next((m.REV for m in mods if hasattr(m, "REV")), DEFAULT_REV)
    date = next((m.DATE for m in mods if hasattr(m, "DATE")), DEFAULT_DATE)
    d = schgen.Design(project_name(board), title, rev, date, COMPANY)
    d.power(*_union(mods, "POWER_NETS"))
    d.intersheet = set(_union(mods, "INTERSHEET"))   # global labels even in a partial (--only) build
    src = ", ".join(f"sheets/{m.__name__.split('.')[-1]}.py" for m in mods)
    d.root_notes = [f"{title}, rev {rev}: generated by keyboard/hardware/design/build.py from {src}. Do not hand-edit.\n"
                    "Architecture of record: keyboard/hardware/design/SPEC.md and nets.py.\n"
                    "Status: captured (schematic generated and gated); not built, not measured."]
    for m in mods:
        m.build(d)
    return d


def erc(out, project, waivers):
    sch = os.path.join(out, project + ".kicad_sch")
    rpt = os.path.join(out, "erc.rpt")
    subprocess.run(["kicad-cli", "sch", "erc", "--severity-all", "-o", rpt, sch], capture_output=True, text=True)
    found = []
    with open(rpt, encoding="utf-8") as f:
        for line in f:
            if line.startswith("["):
                found.append([line.split("]")[0][1:], set()])
            elif found and line.startswith("    @("):
                m = re.search(r"Symbol (\S+) Pin (\S+)", line)
                if m:
                    found[-1][1].add((m.group(1), m.group(2)))
    counts = {}
    for kind, pins in found:
        waived = any(kind == w[0] and (w[1] == "*" or pins and pins <= w[1]) for w in waivers)
        key = "waived " + kind if waived else f"[{kind}]"
        counts[key] = counts.get(key, 0) + 1
    return rpt, counts


def netlist(out, project):
    sch = os.path.join(out, project + ".kicad_sch")
    path = os.path.join(out, project + ".net")
    subprocess.run(["kicad-cli", "sch", "export", "netlist", "-o", path, sch], check=True, capture_output=True)
    return path


def render(out, project, dpi=110):
    """Schematic -> PDF -> one PNG per sheet (for visual review)."""
    sch = os.path.join(out, project + ".kicad_sch")
    rdir = os.path.join(out, "render")
    os.makedirs(rdir, exist_ok=True)
    for f in os.listdir(rdir):                       # no stale pages from an earlier, longer build
        if f.startswith("sheet") and f.endswith(".png"):
            os.remove(os.path.join(rdir, f))
    pdf = os.path.join(rdir, project + "-schematic.pdf")
    subprocess.run(["kicad-cli", "sch", "export", "pdf", "-o", pdf, sch], check=True, capture_output=True)
    subprocess.run(["pdftoppm", "-r", str(dpi), "-png", pdf, os.path.join(rdir, "sheet")], check=True)
    return rdir


def build_board(board, sheets, out, run_erc=True, do_render=False, partial=False):
    schgen.set_uuid_namespace(uuid_namespace(board))
    pcbgen.UUID_NAMESPACE = uuid_namespace(board)
    mods = load_modules(sheets)
    libs = build_libraries(mods, out)
    d = make_design(board, mods)
    errs = d.check()
    if partial:
        errs = [e for e in errs if not any(f"net {n} has only one" in e for n in d.intersheet)]
    single = set(_union(mods, "SINGLE_PIN_NETS"))
    errs = [e for e in errs if not any(f"net {n} has only one" in e for n in single)]
    for e in errs:
        print(f"[{board}] CHECK:", e)
    for w in d.warnings:
        print(f"[{board}] READABILITY:", w)
    d.write(out, extra_sym_libs=libs["sym"], extra_fp_libs=libs["fp"])
    project = project_name(board)
    print(f"[{board}] schematic written to", out)
    if run_erc:
        rpt, counts = erc(out, project, BOARD_ERC_WAIVERS.get(board, []))
        print(f"[{board}] ERC:", counts or "clean", "->", rpt)
        if any(k.startswith("[") for k in counts):
            errs.append(f"{board}: ERC violations {counts}")
        print(f"[{board}] netlist:", netlist(out, project))
    if do_render:
        print(f"[{board}] render:", render(out, project))
    return errs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--board", choices=sorted(PROJECTS), help="build one board only")
    ap.add_argument("--only", nargs="*", help="build only these sheet modules (scratch builds; use --out)")
    ap.add_argument("--out", help="output dir (default keyboard/hardware/kicad/<board>)")
    ap.add_argument("--no-erc", action="store_true")
    ap.add_argument("--render", action="store_true", help="also export PDF + PNG per sheet")
    a = ap.parse_args()
    errs = []
    for board in PROJECTS:
        if a.board and board != a.board:
            continue
        sheets = sheet_modules(board)
        if not sheets:
            msg = f"[{board}] not captured yet: no sheet module ({PROJECTS[board]['sheets']})"
            if a.board:
                print(msg)
                return 1
            print(msg, "- skipped")
            continue
        sel = [s for s in sheets if not a.only or s in a.only]
        if not sel:
            continue
        out = a.out or os.path.join(DEFAULT_OUT, board)
        if a.out and not a.board:
            out = os.path.join(a.out, board)
        errs += build_board(board, sel, out, not a.no_erc, a.render, partial=bool(a.only))
    return 1 if errs else 0


if __name__ == "__main__":
    sys.exit(main())
