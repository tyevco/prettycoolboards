"""tests/zephyr: coupon_desc.h inside Zephyr v4.5.0 on native_sim (slow: three builds, about 30 s here).

* direct: the test coupon's image written to and read from an emulated EEPROM through Zephyr's own eeprom_at2x
  driver, validated with coupon_desc_validate() and Zephyr's crc32_ieee() (CONFIG_CRC);
* mux: the TCA9548A slot mux with five EEPROMs at 0x50 behind it: every EEPROM device is ready with nothing on the
  bus, the device names, and an absent coupon's read failing;
* mux without the init priorities: the build must fail on i2c_tca954x.c's BUILD_ASSERT (a finding for the testbed
  firmware: Zephyr v4.5.0's defaults do not build a TCA954x);
* shell: the lines make_eeprom.py --shell writes, run through Zephyr's own eeprom shell (dummy backend) into the
  emulated EEPROM, which then holds a valid image; and a 17-byte line refused (16 bytes is the shell's limit).

Each zephyr.exe runs in its own build directory: native_sim's simulated flash EEPROM (zephyr,sim-eeprom in the
board's devicetree) writes an eeprom.bin into the working directory.

Emulators are not chips: no write cycle time, no page roll-over, no real mux. Run with `-m slow` or `--run-slow`.
"""

import os
import shutil
import struct
import subprocess

import pytest

import descriptor as D
import make_eeprom as ME

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.join(HERE, "zephyr")
ZEPHYR = os.environ.get("ZEPHYR_BASE", "/root/zephyrproject/zephyr")
WEST_ENV = os.environ.get("COUPON_ZEPHYR_ENV", "/root/zephyrproject/ENV.sh")

pytestmark = [pytest.mark.slow,
              pytest.mark.skipif(not (os.path.isdir(ZEPHYR) and os.path.exists(WEST_ENV) and shutil.which("bash")),
                                 reason="no Zephyr v4.5.0 workspace")]


def write_inc(d):
    with open(os.path.join(HERE, "..", "descriptors", "test-coupon.json"), encoding="utf-8") as fh:
        import json
        desc = json.load(fh)
    img, _ = ME.build(desc, "test-coupon", serial=42, git="0123456789abcdef")
    k = D.decode(img)
    lines = ["/* generated by tests/test_zephyr_app.py from descriptors/test-coupon.json */",
             f"static const uint8_t coupon_image[{len(img)}] = {{"]
    lines += ["\t" + ", ".join(f"0x{b:02x}" for b in img[o:o + 16]) + "," for o in range(0, len(img), 16)]
    lines += ["};", f"#define COUPON_IMAGE_TYPE {D.COUPON_TYPES[k['type']]}",
              f"#define COUPON_IMAGE_SERIAL {k['serial']}u",
              f"#define COUPON_IMAGE_USES 0x{struct.unpack_from('<I', img, 0x20)[0]:08x}u",
              f"#define COUPON_IMAGE_MAX_MA_3V3 {k['rails']['+3V3']['max_ma']}",
              f"#define COUPON_IMAGE_MAX_MA_5V {k['rails']['+5V']['max_ma']}",
              f"#define COUPON_IMAGE_CRC 0x{D.crc32(img[:0xFC]):08x}u", ""]
    (d / "coupon_image.inc").write_text("\n".join(lines))
    cmds = [ln for ln in ME.shell_script(img, "coupon-s1").splitlines() if ln.startswith("eeprom write")]
    (d / "coupon_shell.inc").write_text("/* generated by tests/test_zephyr_app.py: make_eeprom.py --shell coupon-s1 */\n"
                                        "static const char *const coupon_shell_lines[] = {\n"
                                        + "".join(f'\t"{c}",\n' for c in cmds) + "};\n")


def west(build, *extra):
    cmd = (f". {WEST_ENV} && export ZEPHYR_TOOLCHAIN_VARIANT=host && cd {os.path.dirname(ZEPHYR)} && "
           f"west build -p always -b native_sim/native/64 {APP} -d {build} -- " + " ".join(extra))
    return subprocess.run(["bash", "-c", cmd], capture_output=True, text=True, timeout=900)


@pytest.fixture(scope="module")
def inc(tmp_path_factory):
    d = tmp_path_factory.mktemp("inc")
    write_inc(d)
    return d


def _run(build):
    # cwd: the board's simulated flash EEPROM creates eeprom.bin in the working directory (it once landed in the
    # repository root this way)
    out = subprocess.run([os.path.join(build, "zephyr", "zephyr.exe")], capture_output=True, text=True, timeout=120,
                         cwd=str(build))
    return out.stdout + out.stderr


def test_direct(tmp_path, inc):
    r = west(tmp_path / "b", f"-DCOUPON_IMAGE_INC={inc}", f"-DEXTRA_DTC_OVERLAY_FILE={APP}/direct.overlay",
             f"-DEXTRA_CONF_FILE={APP}/direct.conf")
    assert r.returncode == 0, r.stdout[-3000:] + r.stderr[-3000:]
    out = _run(tmp_path / "b")
    assert "SUITE PASS - 100.00% [coupon_direct]: pass = 3, fail = 0" in out, out[-3000:]


def test_mux(tmp_path, inc):
    r = west(tmp_path / "b", f"-DCOUPON_IMAGE_INC={inc}", f"-DEXTRA_DTC_OVERLAY_FILE={APP}/mux.overlay",
             f"-DEXTRA_CONF_FILE={APP}/mux.conf")
    assert r.returncode == 0, r.stdout[-3000:] + r.stderr[-3000:]
    out = _run(tmp_path / "b")
    assert "SUITE PASS - 100.00% [coupon_mux]: pass = 3, fail = 0" in out, out[-3000:]
    assert "COUPON names: eeprom@50 coupon-s2 coupon-s3 coupon-s4 coupon-s5" in out


def test_mux_default_priorities_do_not_build(tmp_path, inc):
    r = west(tmp_path / "b", f"-DCOUPON_IMAGE_INC={inc}", f"-DEXTRA_DTC_OVERLAY_FILE={APP}/mux.overlay",
             f"-DEXTRA_CONF_FILE={APP}/mux-default.conf")
    assert r.returncode != 0
    assert "I2C multiplexer channels must be initialized after their root" in r.stdout + r.stderr


def test_shell_lines_write_the_image(tmp_path, inc):
    r = west(tmp_path / "b", f"-DCOUPON_IMAGE_INC={inc}", f"-DEXTRA_DTC_OVERLAY_FILE={APP}/direct.overlay",
             f"-DEXTRA_CONF_FILE={APP}/shell.conf")
    assert r.returncode == 0, r.stdout[-3000:] + r.stderr[-3000:]
    out = _run(tmp_path / "b")
    assert "SUITE PASS - 100.00% [coupon_shell]: pass = 2, fail = 0" in out, out[-3000:]
    assert "SUITE PASS - 100.00% [coupon_direct]: pass = 3, fail = 0" in out, out[-3000:]
    assert "COUPON shell: 16 lines accepted, image valid" in out
