# --- C header ---------------------------------------------------------------------------------------------------
def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_header(m):
    h = m.hash()
    ids = m.rail_ids()
    L = []
    w = L.append
    w("/*")
    for line in GENERATED_LINES:
        w(f" * {line}")
    w(f" * nets.py rev {m.rev} {m.date}.")
    w(" *")
    w(" * The pin, expander, monitor and budget map of the rev A testbed motherboard (board kbd_testbed_a), as plain")
    w(" * C constants for code that does not go through the devicetree: the bring-up checks, the lib's tests, and")
    w(" * later the scan engine's register-level GPIO and ADC setup. The board is designed, NOT BUILT.")
    w(" *")
    w(" * SPDX-License-Identifier: Apache-2.0")
    w(" */")
    w("#ifndef TB_BOARD_MAP_H_")
    w("#define TB_BOARD_MAP_H_")
    w("")
    w(f'#define TB_MAP_HASH "{h}"')
    w(f'#define TB_MAP_NETS_REV {c_str(m.rev)}')
    w(f'#define TB_MAP_NETS_DATE {c_str(m.date)}')
    w(f'#define TB_MAP_MCU {c_str(m.mcu_name)}')
    w(f"#define TB_NUM_SLOTS {len(m.slots)}")
    w("")
    w("/* --- MCU pins (nets.MCU_PINS, nets.MCU_FUNC) ------------------------------------------------------------- */")
    w("/* TB_PIN_<net>: port index (A = 0 ... H = 7), pin number, LQFP100 pin number. */")
    w("#define TB_PORT_INDEX(letter) ((letter) - 'A')")
    nets_sorted = sorted(m.net_pin.items(), key=lambda kv: (gpio_of(kv[1])[0], gpio_of(kv[1])[1]))
    width = max(len(ident(n)) for n in m.net_pin) + 12
    for net, pin in nets_sorted:
        port, num = gpio_of(pin)
        base = f"TB_PIN_{ident(net)}"
        w(f"#define {base + '_PORT':<{width}} {PORTS.index(port)}  /* P{port}{num} */")
        w(f"#define {base + '_PIN':<{width}} {num}")
        w(f"#define {base + '_LQFP':<{width}} {m.lqfp_of[pin]}")
    w("")
    w("/* Every used MCU GPIO: { port index, pin, LQFP pin, net, function, mode } (mode: nets.MCU_FUNC). */")
    w(f"#define TB_MCU_GPIO_COUNT {len(nets_sorted)}")
    w("#define TB_MCU_GPIO_TABLE { \\")
    for i, (net, pin) in enumerate(nets_sorted):
        port, num = gpio_of(pin)
        func, mode, _node = m.mcu_func[pin]
        sep = "," if i + 1 < len(nets_sorted) else ""
        w(f"\t{{ {PORTS.index(port)}, {num}, {m.lqfp_of[pin]}, {c_str(net)}, {c_str(func)}, {c_str(mode)} }}{sep} \\")
    w("}")
    w("")
    w("/* EXTI line per interrupt input (SPEC §5.3; nets.EXTI_INPUTS). */")
    for net in m.exti_inputs:
        w(f"#define TB_EXTI_{ident(net)} {gpio_of(m.net_pin[net])[1]}")
    w("")
    w("/* --- Rails (numbering shared with keyboard/firmware/lib, tb/rails.h) ------------------------------------- */")
    for rail, i in sorted(ids.items(), key=lambda kv: kv[1]):
        w(f"#define TB_RAIL_ID_{ident(rail)} {i}")
    w(f"#define TB_RAIL_ID_COUNT {len(ids)}")
    w("")
    w("/* --- I/O expanders (nets.EXPANDERS; TCA9535, nxp,pca95xx pin = 8 x port + bit) --------------------------- */")
    w(f"#define TB_EXP_COUNT {len(m.exp_refs)}")
    for i, ref in enumerate(m.exp_refs):
        w(f"#define TB_EXP_{ref.replace('U_', '')}_INDEX {i}")
        w(f"#define TB_EXP_{ref.replace('U_', '')}_ADDR 0x{m.exp_addr[ref]:02X}")
    w("/* TB_EXPNET_<net>: expander index, driver pin; direction 1 = output; active low; restored level (outputs). */")
    for net in sorted(m.exp_net, key=lambda n: (m.exp_net[n][0], m.exp_net[n][1])):
        ref, idx = m.exp_net[net]
        d, al, safe = m.exp_role(net)
        base = f"TB_EXPNET_{ident(net)}"
        w(f"#define {base}_EXP {m.exp_refs.index(ref)}  /* {ref} P{idx // 8}{idx % 8} */")
        w(f"#define {base}_PIN {idx}")
        w(f"#define {base}_OUT {1 if d == 'out' else 0}")
        w(f"#define {base}_ACTIVE_LOW {1 if al else 0}")
        if safe is not None:
            w(f"#define {base}_SAFE_LEVEL {safe}")
    w("")
    regs = m.exp_registers()
    w("/* Restored state (SPEC §3.5, §8.4): every rail off, every bus switch open, G4/G5 low, LEDs off, the mux")
    w(" * running, the KVM coupon held in reset. Per expander: output-pin mask, output register, configuration")
    w(" * register (TCA9535: 1 = input). Input pins keep their power-up output-register bit (1). */")
    w("#define TB_EXP_ADDRS { " + ", ".join(f"0x{m.exp_addr[r]:02X}" for r in m.exp_refs) + " }")
    w("#define TB_EXP_OUTPUT_MASK { " + ", ".join(f"0x{regs[r][0]:04X}" for r in m.exp_refs) + " }")
    w("#define TB_EXP_SAFE_OUTPUT { " + ", ".join(f"0x{regs[r][1]:04X}" for r in m.exp_refs) + " }")
    w("#define TB_EXP_SAFE_CONFIG { " + ", ".join(f"0x{regs[r][2]:04X}" for r in m.exp_refs) + " }")
    w("/* The TCA9535's power-on state (SCPS201D): every pin an input, output register 0xFFFF. */")
    w("#define TB_EXP_POR_CONFIG 0xFFFF")
    w("#define TB_EXP_POR_OUTPUT 0xFFFF")
    w("/* Expander nets, by expander and driver pin (NULL = unused pin). */")
    w("#define TB_EXP_NET_NAMES { \\")
    for i, ref in enumerate(m.exp_refs):
        names = ["NULL"] * 16
        for pname, net in m.expanders[ref].items():
            if net:
                names[exp_pin_index(pname)] = c_str(net)
        sep = "," if i + 1 < len(m.exp_refs) else ""
        w(f"\t{{ {', '.join(names)} }}{sep} \\")
    w("}")
    w("")
    w("/* --- Per slot (SPEC §4.4) ----------------------------------------------------------------------------------- */")
    w("/* Lanes: { primary ADC, channel }, and every alternate { ADC, channel } (0, 0 = none), per lane AN0..AN3. */")
    w("#define TB_SLOT_LANE_PRIMARY { \\")
    for i, n in enumerate(m.slots):
        cells = []
        for k in range(4):
            _p, (a, c), _o = m.lane(n, k)
            cells.append(f"{{ {a}, {c} }}")
        sep = "," if i + 1 < len(m.slots) else ""
        w(f"\t{{ {', '.join(cells)} }}{sep} \\")
    w("}")
    w("#define TB_LANE_MAX_ALT 2")
    w("#define TB_SLOT_LANE_ALT { \\")
    for i, n in enumerate(m.slots):
        lanes = []
        for k in range(4):
            _p, _pr, others = m.lane(n, k)
            if len(others) > 2:
                raise GenError("more than two alternate converters on one lane")
            cells = [f"{{ {a}, {c} }}" for a, c in others] + ["{ 0, 0 }"] * (2 - len(others))
            lanes.append("{ " + ", ".join(cells) + " }")
        sep = "," if i + 1 < len(m.slots) else ""
        w(f"\t{{ {', '.join(lanes)} }}{sep} \\")
    w("}")
    w("/* Lane resolution in bits by ADC: ADC1/ADC2 14-bit, ADC4 12-bit (DS13543 Tables 97, 100). */")
    w("#define TB_ADC_RES_BITS(adc) ((adc) == 4 ? 12 : 14)")
    w(f"#define TB_ADC_VREF_MV {VREF_MV}")
    w("/* The board devicetree's lane acquisition times, in the SoC's sampling-times ticks. */")
    w(f"#define TB_ADC12_ACQ_TICKS {ADC12_ACQ_TICKS}")
    w(f"#define TB_ADC4_ACQ_TICKS {ADC4_ACQ_TICKS}")
    w("")

    def ina_row(rail):
        a = m.ina_by_rail[rail]
        return a
    w("/* --- INA226 monitors (nets.INA226_RAILS, INA226_CURRENT_LSB_UA; SPEC §3.4) ----------------------------- */")
    w("/* { address, rail, shunt uOhm, current LSB uA, CAL (Zephyr's formula), rail id or -1, coupon rule mA or 0,")
    w(" *   switch trip min / typ / max mA or 0 } */")
    w(f"#define TB_INA226_COUNT {len(m.ina)}")
    w("#define TB_INA226_TABLE { \\")
    for i, addr in enumerate(sorted(m.ina)):
        rail, shunt, rule = m.ina[addr]
        lsb = m.ina_lsb[addr]
        uohm = round(shunt * 1e6)
        cal = zephyr_ina226_cal(lsb, uohm)
        trip = m.trip.get(rail, (0, 0, 0))
        rid = ids.get(rail, -1)
        sep = "," if i + 1 < len(m.ina) else ""
        w(f"\t{{ 0x{addr:02X}, {c_str(rail)}, {uohm}, {lsb}, {cal}, {rid}, {round((rule or 0) * 1000)}, "
          f"{round(trip[0] * 1000)}, {round(trip[1] * 1000)}, {round(trip[2] * 1000)} }}{sep} \\")
    w("}")
    for rail in ("VSYS", "+3V3_MCU", "+3V3_USB"):
        w(f"#define TB_INA226_ADDR_{ident(rail)} 0x{ina_row(rail):02X}")
    w("/* The INA226 serving each rail id (3V3_S1..S5, 5V_S1..S5); the KVM rail has none (SPEC §3.1). */")
    w("#define TB_RAIL_INA226_ADDR { " + ", ".join(
        f"0x{m.ina_by_rail[r]:02X}" for r, _i in sorted(ids.items(), key=lambda kv: kv[1]) if r in m.ina_by_rail)
      + ", 0x00 }")
    w("")
    w("/* --- Budgets and rules (nets.vsys_budget, TYPEC_BUDGET, SWITCH_TRIP; SPEC §3.1, §3.2) ------------------ */")
    w(f"#define TB_VSYS_BUDGET_MAX_MA {round(m.vsys_max * 1000)}")
    w(f"#define TB_VSYS_BUDGET_UNCONFIGURED_MA {round(m.vsys_unconf * 1000)}")
    for adv in ("default", "1.5A", "3.0A", "accessory", "not attached", "unreadable"):
        key = {"default": "DEFAULT", "1.5A": "1A5", "3.0A": "3A0", "accessory": "ACCESSORY",
               "not attached": "NOT_ATTACHED", "unreadable": "UNREADABLE"}[adv]
        w(f"#define TB_TYPEC_BUDGET_{key}_MA {round(m.typec_budget[adv] * 1000)}")
    w(f"#define TB_SLOT_LDO_MA {SLOT_LDO_MA}  /* SPEC §3.2 (not in nets.py) */")
    w(f"#define TB_BASE_LOAD_MA {BASE_LOAD_MA}  /* SPEC §3.2 estimate (not in nets.py) */")
