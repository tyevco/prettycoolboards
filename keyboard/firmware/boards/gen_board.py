    vt = m.trip["VSYS"]
    w(f"#define TB_VSYS_TRIP_MA {{ {round(vt[0] * 1000)}, {round(vt[1] * 1000)}, {round(vt[2] * 1000)} }}")
    w("")
    w("/* --- I2C addresses ----------------------------------------------------------------------------------------- */")
