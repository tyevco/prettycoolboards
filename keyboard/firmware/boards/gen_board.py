def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--nets", type=pathlib.Path, default=DEFAULT_NETS, help="nets.py to read")
    ap.add_argument("--check", action="store_true", help="fail if a committed generated file differs")
    ap.add_argument("--diff", action="store_true", help="with --check: print a unified diff per stale file")
    args = ap.parse_args(argv)
    try:
        files = render_all(args.nets)
    except GenError as e:
        print(f"gen_board: {e}", file=sys.stderr)
        return 2
    if args.check:
        stale = []
        for path, text in files.items():
            cur = path.read_text(encoding="utf-8") if path.exists() else None
            if cur != text:
                stale.append(path)
                if args.diff:
                    sys.stdout.writelines(difflib.unified_diff(
                        (cur or "").splitlines(keepends=True), text.splitlines(keepends=True),
                        f"{path.relative_to(REPO)} (committed)", f"{path.relative_to(REPO)} (from nets.py)"))
        missing = [p for p in HAND_WRITTEN if not (BOARD_DIR / p).exists()]
        for p in stale:
            print(f"gen_board: {p.relative_to(REPO)} is stale or missing", file=sys.stderr)
        for p in missing:
            print(f"gen_board: hand-written {BOARD_DIR.relative_to(REPO) / p} is missing", file=sys.stderr)
        if stale or missing:
            print("gen_board: run python3 keyboard/firmware/boards/gen_board.py", file=sys.stderr)
            return 1
        print(f"gen_board: {len(files)} generated files match nets.py")
        return 0
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print(f"gen_board: wrote {path.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
