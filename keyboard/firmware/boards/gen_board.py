class GenError(Exception):
    pass


def gpio_of(pin):
    """'PC14-OSC32_IN' -> ('C', 14); None for a supply pin."""
    m = re.match(r"^P([A-H])(\d{1,2})(?:-|$)", pin)
    return (m.group(1), int(m.group(2))) if m else None


def exp_pin_index(pname):
    """TCA9535 'P14' -> the nxp,pca95xx driver's pin number 12 (port 1 is pins 8-15)."""
    m = re.match(r"^P([01])([0-7])$", pname)
    if not m:
        raise GenError(f"expander pin {pname} is not P00-P17")
    return int(m.group(1)) * 8 + int(m.group(2))


def ident(net):
    """A C identifier fragment for a net name: '+3V3_S1' -> 'P3V3_S1', 'S1_G0' -> 'S1_G0'."""
    s = net.upper().replace("+", "P")
    return re.sub(r"[^A-Z0-9]", "_", s).strip("_")


def dts_label(net):
    return ident(net).lower()


class Model:
    """Everything the generator needs, read once from nets.py and checked for what the board relies on."""

    def __init__(self, nets_path):
        self.src = nets_path.read_bytes()
        ns = runpy.run_path(str(nets_path))
        self.ns = ns
        problems = ns["check"]()
        if problems:
            raise GenError("nets.check() fails:\n  " + "\n  ".join(problems))
        self.rev, self.date = ns["REV"], ns["DATE"]
        self.slots = list(ns["SLOTS"])
        self.mcu_pins = ns["MCU_PINS"]
        self.mcu_func = ns["MCU_FUNC"]
        self.lqfp = ns["LQFP100"]
        self.slot_mcu = ns["SLOT_MCU"]
        self.lane_adc = ns["LANE_ADC"]
        self.expanders = ns["EXPANDERS"]
        self.exp_i2c = ns["EXPANDER_I2C"]
        self.reset_state = ns["EXPANDER_RESET_STATE"]
        self.ina = ns["INA226_RAILS"]
        self.ina_lsb = ns["INA226_CURRENT_LSB_UA"]
        self.trip = ns["SWITCH_TRIP"]
        self.typec = ns["TYPEC"]
        self.typec_addr = ns["typec_address"]()
        self.typec_budget = ns["TYPEC_BUDGET"]
        self.vsys_max = ns["VSYS_BUDGET_MAX"]
        self.vsys_unconf = ns["VSYS_BUDGET_UNCONFIGURED"]
        self.tusb_ready_s = ns["TUSB320_I2C_READY_S"]
        self.i2c_slot = ns["I2C_SLOT_UPSTREAM"]
        self.coupon_known = ns["COUPON_I2C_KNOWN"]
        self.slot_pins = ns["SLOT_PINS"]
        self.exti_inputs = ns["EXTI_INPUTS"]
        self.mcu_name = ns["MCU"]
        self.net_pin = {net: pin for pin, net in self.mcu_pins.items() if net and gpio_of(pin)}
        self.lqfp_of = {name: num for num, name in self.lqfp.items()}
        # expander net -> (expander ref, driver pin index)
        self.exp_net = {}
        for ref, pins in self.expanders.items():
            for pname, net in pins.items():
                if net:
                    self.exp_net[net] = (ref, exp_pin_index(pname))
        self.exp_refs = sorted(self.expanders)
        self.exp_addr = {}
        for addr, desc in self.exp_i2c.items():
            ref = desc.split()[0]
            self.exp_addr[ref] = addr
        if sorted(self.exp_addr) != self.exp_refs:
            raise GenError(f"EXPANDER_I2C refs {sorted(self.exp_addr)} != EXPANDERS {self.exp_refs}")
        self.mux_addr = next((a for a, d in self.i2c_slot.items() if "TCA9548A" in d), None)
        if self.mux_addr is None:
            raise GenError("no TCA9548A in I2C_SLOT_UPSTREAM")
        self.eeprom_addr = next((a for a, d in self.coupon_known.items() if "descriptor" in d), None)
        if self.eeprom_addr is None:
            raise GenError("no descriptor EEPROM address in COUPON_I2C_KNOWN")
        if self.typec_addr is None:
            raise GenError("U_CC has no I2C address")
        if self.typec["bus"] != "I2C_PM":
            raise GenError("this generator puts U_CC on I2C1 (I2C_PM); nets.TYPEC moved it: update gen_board.py")
        self.ina_by_rail = {r[0]: a for a, r in self.ina.items()}
        self.required()

    def required(self):
        need = ["CON_TX", "CON_RX", "USB_DM", "USB_DP", "USB_SOF", "I2C_PM_SCL", "I2C_PM_SDA", "I2C_SLOT_SCL",
                "I2C_SLOT_SDA", "SLOT_SCK", "SLOT_MISO", "SLOT_MOSI", "SLOT_SYNC", "RIG_MARK", "RIG_TRIG",
                "EXP_INT_N", "LED_N", "KVM_TX", "KVM_RX", "SWDIO", "SWCLK", "SWO"]
        missing = [n for n in need if n not in self.net_pin]
        exp_need = ["MUX_RST_N", "KVM_RST_N", "SLOT_FAULT_N", "PM_ALERT_N", "VSYS_PG", "S5_PG", "USBC_INT_N",
                    "KVM_PRESENT_N", "EN_5V_KVM",
                    *[f"{p}_S{n}" for n in self.slots for p in ("EN_3V3", "EN_5V", "BUSEN_N", "LED")],
                    *[f"S{n}_PRESENT_N" for n in self.slots]]
        missing += [n for n in exp_need if n not in self.exp_net]
        for n in self.slots:
            for r in (f"+3V3_S{n}", f"+5V_S{n}"):
                if r not in self.ina_by_rail:
                    missing.append(f"INA226 for {r}")
        for r in ("VSYS", "+3V3_MCU", "+3V3_USB"):
            if r not in self.ina_by_rail:
                missing.append(f"INA226 for {r}")
        if missing:
            raise GenError("nets.py lacks what the board needs: " + ", ".join(missing))

    # --- derived facts ------------------------------------------------------------------------------------------
    def exp_role(self, net):
        """(direction, active_low, safe_level) for an expander net; safe_level is the physical level the restore
        drives (None for inputs). Outputs are the nets EXPANDER_RESET_STATE gives a holding resistor (SPEC §3.5)."""
        rule = None
        for key, text in self.reset_state.items():
            if (key.endswith("_") and net.startswith(key)) or (key.startswith("_") and net.endswith(key)) \
                    or net == key or (key == "LED_S" and net.startswith("LED_S")):
                rule = (key, text)
                break
        if rule is None:
            active_low = net.endswith("_N")
            return ("in", active_low, None)
        key, text = rule
        t = text.lower()
        if key == "LED_S":
            # "LED off (cathode to the pin)": the pin sinks the LED, so low = lit, and the safe level is high
            return ("out", True, 1)
        if "pull-down" in t:
            safe = 0
        elif "pull-up" in t:
            safe = 1
        else:
            raise GenError(f"expander reset state for {key} names no pull-up or pull-down: {text!r}")
        return ("out", net.endswith("_N"), safe)

    def exp_registers(self):
        """Per expander: (output mask, restored output register, restored configuration register).
        TCA9535 configuration: 1 = input. Bits of input pins in the output register keep the power-up 1."""
        regs = {}
        for ref in self.exp_refs:
            out_mask, out_val = 0, 0xFFFF
            for pname, net in self.expanders[ref].items():
                if not net:
                    continue
                bit = exp_pin_index(pname)
                d, _al, safe = self.exp_role(net)
                if d == "out":
                    out_mask |= 1 << bit
                    if safe == 0:
                        out_val &= ~(1 << bit)
            regs[ref] = (out_mask, out_val & 0xFFFF, (~out_mask) & 0xFFFF)
        return regs

    def rail_ids(self):
        """Rail numbering shared with keyboard/firmware/lib (tb/rails.h): 3V3_S1..S5 = 0..4, 5V_S1..S5 = 5..9,
        5V_KVM = 10."""
        ids = {}
        for i, n in enumerate(self.slots):
            ids[f"+3V3_S{n}"] = i
            ids[f"+5V_S{n}"] = len(self.slots) + i
        ids["+5V_KVM"] = 2 * len(self.slots)
        return ids

    def lane(self, n, k):
        """Slot n lane k -> (pin, primary (adc, channel), [alternates (adc, channel)])."""
        pin = self.slot_mcu[n][f"AN{k}"]
        chans = []
        for c in self.lane_adc[pin]:
            m = re.match(r"ADC(\d)_IN(\d+)$", c)
            chans.append((int(m.group(1)), int(m.group(2))))
        return pin, chans[0], chans[1:]

    def hash(self):
        return hashlib.sha256(self.src + pathlib.Path(__file__).read_bytes()).hexdigest()[:16]


def zephyr_ina226_cal(lsb_ua, shunt_uohm):
    """CAL exactly as Zephyr v4.5.0's ti,ina226 driver computes it: DIV_ROUND_CLOSEST(5120000000, LSB x R) in
    integers (drivers/sensor/ti/ina2xx/ina226.c, INA226_DT_CAL), not Python's round(), which rounds a half to even."""
    den = lsb_ua * shunt_uohm
    return (5120000000 + den // 2) // den


# --- devicetree --------------------------------------------------------------------------------------------------
def gpio_ref(pin, flags):
    port, num = gpio_of(pin)
    return f"<&gpio{port.lower()} {num} {flags}>"


def exp_ref(model, net, flags):
    ref, idx = model.exp_net[net]
    return f"<&{ref.lower()} {idx} {flags}>"


def flags_for(active_low):
    return "GPIO_ACTIVE_LOW" if active_low else "GPIO_ACTIVE_HIGH"


def _root_nodes(m, w):
    """The testbed and slot nodes under / (the board dts and the native_sim overlay share them)."""
    np = m.net_pin
    # motherboard signals
    tb = {
        "exp-int-gpios": gpio_ref(np["EXP_INT_N"], "GPIO_ACTIVE_LOW"),
        "slot-sync-gpios": gpio_ref(np["SLOT_SYNC"], "GPIO_ACTIVE_HIGH"),
        "rig-mark-gpios": gpio_ref(np["RIG_MARK"], "GPIO_ACTIVE_HIGH"),
        "rig-trig-gpios": gpio_ref(np["RIG_TRIG"], "GPIO_ACTIVE_HIGH"),
    }
    for net in ("SLOT_FAULT_N", "PM_ALERT_N", "VSYS_PG", "S5_PG", "USBC_INT_N", "KVM_PRESENT_N", "MUX_RST_N",
                "KVM_RST_N", "EN_5V_KVM"):
        _d, al, _s = m.exp_role(net)
        tb[f"{net.lower().replace('_', '-')}-gpios".replace("-n-gpios", "-gpios")] = exp_ref(m, net, flags_for(al))
    w("\t/* The motherboard's own signals (SPEC §3, §4.3, §7.3), for the board service and the bring-up app. */")
    w("\ttestbed: testbed {")
    w(f'\t\tcompatible = "{VENDOR},kbd-testbed";')
    for k in sorted(tb):
        w(f"\t\t{k} = {tb[k]};")
    w("\t\tina226-vsys = <&ina_vsys>;")
    w("\t\tina226-mcu = <&ina_p3v3_mcu>;")
    w("\t\tina226-usb = <&ina_p3v3_usb>;")
    w("\t\ttypec = <&u_cc>;")
    w("\t\tslot-mux = <&u_mux>;")
    w("\t\tkvm-i2c = <&mux_ch5>;")
    w(f"\t\tslot-ldo-milliamps = <{SLOT_LDO_MA}>;")
    w(f"\t\tbase-load-milliamps = <{BASE_LOAD_MA}>;")
    w(f"\t\tvsys-budget-max-milliamps = <{round(m.vsys_max * 1000)}>;")
    w(f"\t\tvsys-budget-unconfigured-milliamps = <{round(m.vsys_unconf * 1000)}>;")
    vt = m.trip["VSYS"]
    w(f"\t\tvsys-trip-milliamps = <{' '.join(str(round(x * 1000)) for x in vt)}>;")
    w(f"\t\tkvm-trip-milliamps = <{' '.join(str(round(x * 1000)) for x in KVM_TRIP_A)}>;")
    w(f"\t\tkvm-rule-milliamps = <{round(KVM_RULE_A * 1000)}>;")
    w("\t};")
    w("")
    # slots
    w("\t/* The five coupon slots (SPEC §4.2-§4.4). Lanes: io-channels = AN0..AN3 on their primary converter;")
    w("\t * alt-adc-channels = <lane adc channel> for every other converter that reaches the lane's pin. */")
    w("\tslots {")
    ids = m.rail_ids()
    for n in m.slots:
        sm = m.slot_mcu[n]
        w(f"\t\tslot{n}: slot-{n} {{")
        w(f'\t\t\tcompatible = "{VENDOR},coupon-slot";')
        w(f"\t\t\tslot = <{n}>;")
        prim, alts = [], []
        for k in range(4):
            _pin, (adc, ch), others = m.lane(n, k)
            prim.append(f"<&adc{adc} {ch}>")
            for (a2, c2) in others:
                alts.append(f"{k} {a2} {c2}")
        w(f"\t\t\tio-channels = {', '.join(prim)};")
        w('\t\t\tio-channel-names = "AN0", "AN1", "AN2", "AN3";')
        if alts:
            w(f"\t\t\talt-adc-channels = <{'  '.join(alts)}>;")
        gl = []
        for g in range(6):
            sig = f"G{g}"
            if sig in sm:
                gl.append(gpio_ref(sm[sig], "GPIO_ACTIVE_HIGH"))
            else:
                gl.append(exp_ref(m, f"S{n}_{sig}", "GPIO_ACTIVE_HIGH"))
        w(f"\t\t\tg-gpios = {', '.join(gl)};")
        w(f"\t\t\tcs-gpios = {gpio_ref(sm['CS0_N'], 'GPIO_ACTIVE_LOW')}, {gpio_ref(sm['CS1_N'], 'GPIO_ACTIVE_LOW')};")
        w(f"\t\t\tirq-gpios = {gpio_ref(sm['IRQ_N'], 'GPIO_ACTIVE_LOW')};")
        if "BKIN" in m.mcu_func.get(sm["IRQ_N"], ("",))[0]:
            w("\t\t\t/* TIM1_BKIN: never gpio_pin_configure() it while TIM1 runs (SPEC §5.3). */")
            w("\t\t\tirq-is-tim1-bkin;")
        w(f"\t\t\tpresent-gpios = {exp_ref(m, f'S{n}_PRESENT_N', 'GPIO_ACTIVE_LOW')};")
        w(f"\t\t\ten-3v3-gpios = {exp_ref(m, f'EN_3V3_S{n}', 'GPIO_ACTIVE_HIGH')};")
        w(f"\t\t\ten-5v-gpios = {exp_ref(m, f'EN_5V_S{n}', 'GPIO_ACTIVE_HIGH')};")
        w(f"\t\t\tbusen-gpios = {exp_ref(m, f'BUSEN_N_S{n}', 'GPIO_ACTIVE_LOW')};")
        _d, led_al, _s = m.exp_role(f"LED_S{n}")
        w(f"\t\t\tled-gpios = {exp_ref(m, f'LED_S{n}', flags_for(led_al))};")
        if n == m.slots[-1]:
            _d, al, _s = m.exp_role("S5_PG")
            w(f"\t\t\tpg-5v-gpios = {exp_ref(m, 'S5_PG', flags_for(al))};")
        w(f"\t\t\tina226-3v3 = <&ina_p3v3_s{n}>;")
        w(f"\t\t\tina226-5v = <&ina_p5v_s{n}>;")
        w(f"\t\t\ti2c-channel = <&mux_ch{n - 1}>;")
        r3 = m.ina[m.ina_by_rail[f"+3V3_S{n}"]][2]
        r5 = m.ina[m.ina_by_rail[f"+5V_S{n}"]][2]
        w(f"\t\t\trule-3v3-milliamps = <{round(r3 * 1000)}>;")
        w(f"\t\t\trule-5v-milliamps = <{round(r5 * 1000)}>;")
        w(f"\t\t\ttrip-3v3-milliamps = <{' '.join(str(round(x * 1000)) for x in m.trip[f'+3V3_S{n}'])}>;")
        w(f"\t\t\ttrip-5v-milliamps = <{' '.join(str(round(x * 1000)) for x in m.trip[f'+5V_S{n}'])}>;")
        w(f"\t\t\trail-3v3 = <{ids[f'+3V3_S{n}']}>;")
        w(f"\t\t\trail-5v = <{ids[f'+5V_S{n}']}>;")
        w("\t\t};")
        if n != m.slots[-1]:
            w("")
    w("\t};")


def _i2c1_children(m, w):
    """I2C1's devices: the expanders, the 13 INA226s, U_CC."""
    np = m.net_pin
    regs = m.exp_registers()
    for ref in m.exp_refs:
        addr = m.exp_addr[ref]
        om, ov, oc = regs[ref]
        w(f"\t/* {m.exp_i2c[addr]}. Restored outputs 0x{om:04X}, output register 0x{ov:04X}, configuration")
        w(f"\t * 0x{oc:04X}. nxp,pca95xx with neither has-pud nor has-interrupt-mask-reg (SPEC §8.4). */")
        w(f"\t{ref.lower()}: gpio@{addr:x} {{")
        w('\t\tcompatible = "nxp,pca95xx";')
        w(f"\t\treg = <0x{addr:02x}>;")
        w("\t\tgpio-controller;")
        w("\t\t#gpio-cells = <2>;")
        w("\t\tngpios = <16>;")
        if ref == m.exp_net["USBC_INT_N"][0]:
            w(f"\t\tinterrupt-gpios = {gpio_ref(np['EXP_INT_N'], 'GPIO_ACTIVE_LOW')};")
        w("\t};")
        w("")
    for addr in sorted(m.ina):
        rail, shunt, rule = m.ina[addr]
        lsb = m.ina_lsb[addr]
        cal = zephyr_ina226_cal(lsb, round(shunt * 1e6))
        w(f"\t/* {rail}: {shunt:g} ohm shunt, current LSB {lsb} uA (CAL {cal}), full scale "
          f"{0.08192 / shunt * 1000:.0f} mA. */")
        w(f"\tina_{dts_label(rail)}: ina226@{addr:x} {{")
        w('\t\tcompatible = "ti,ina226";')
        w(f"\t\treg = <0x{addr:02x}>;")
        w(f"\t\tcurrent-lsb-microamps = <{lsb}>;")
        w(f"\t\trshunt-micro-ohms = <{round(shunt * 1e6)}>;")
        w("\t};")
        w("")
    w(f"\t/* U_CC {m.typec['part']}: Type-C source advertisement, read only (SPEC §3.8, §8.4). Its INT_N reaches")
    w(f"\t * the MCU through {m.exp_net['USBC_INT_N'][0]} (no MCU pin). Zephyr v4.5.0 has no driver for it. */")
    w(f"\tu_cc: typec@{m.typec_addr:x} {{")
    w(f'\t\tcompatible = "{VENDOR},tusb320";')
    w(f"\t\treg = <0x{m.typec_addr:02x}>;")
    w(f"\t\tint-gpios = {exp_ref(m, 'USBC_INT_N', 'GPIO_ACTIVE_LOW')};")
    w(f"\t\ti2c-ready-ms = <{round(m.tusb_ready_s * 1000)}>;")
    w(f"\t\tdecide-ms = <{TUSB320_DECIDE_MS}>;")
    w("\t};")


def _mux_node(m, w):
    """The TCA9548A and its eight channel nodes on I2C4."""
    w(f"\t/* {m.i2c_slot[m.mux_addr]}. The driver never pulses RESET (it only deasserts it) and starts")
    w("\t * its channel cache at 0 without writing the device: after a warm reset the board service deselects")
    w("\t * the mux itself (SPEC §3.5, §8.4). idle-disconnect: no channel stays selected between transfers. */")
    w(f"\tu_mux: mux@{m.mux_addr:x} {{")
    w('\t\tcompatible = "ti,tca9548a";')
    w(f"\t\treg = <0x{m.mux_addr:02x}>;")
    w("\t\t#address-cells = <1>;")
    w("\t\t#size-cells = <0>;")
